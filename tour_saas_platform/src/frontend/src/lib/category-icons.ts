export const LUCIDE_ICON_MAP: Record<string, LucideIcon> = Object.fromEntries(
  CURATED_LUCIDE_ICONS.map(({ name, icon }) => [name, icon]),
)

export type ParsedIcon =
  | { type: 'lucide'; value: string }
  | { type: 'url'; value: string }
  | { type: 'custom'; value: string }
  | { type: 'media'; value: string }

const URL_LIKE = /^(https?:\/\/|\/)/i

/** Parse stored icon identifier into type + payload. */
export function parseCategoryIcon(icon: string | null | undefined): ParsedIcon | null {
  if (!icon?.trim()) return null

  const idx = icon.indexOf(':')
  if (idx <= 0) return null

  const prefix = icon.slice(0, idx)
  const value = icon.slice(idx + 1)
  if (!value) return null

  switch (prefix) {
    case 'lucide':
      return { type: 'lucide', value }
    case 'url':
      return { type: 'url', value }
    case 'media':
      return { type: 'media', value }
    case 'custom':
      return URL_LIKE.test(value) ? { type: 'url', value } : { type: 'custom', value }
    default:
      return null
  }
}

export function getLucideIcon(name: string): LucideIcon | undefined {
  return LUCIDE_ICON_MAP[name]
}

/** Human-readable label for UI. */
export function formatCategoryIconLabel(icon: string | null | undefined): string {
  const parsed = parseCategoryIcon(icon)
  if (!parsed) return 'No icon selected'

  switch (parsed.type) {
    case 'lucide':
      return parsed.value
    case 'url':
      return parsed.value.length > 40 ? `${parsed.value.slice(0, 37)}…` : parsed.value
    case 'custom':
      return parsed.value
    case 'media':
      return `Media ${parsed.value.slice(0, 8)}…`
  }
}

export function buildLucideIconValue(name: string): string {
  return `lucide:${name}`
}

export function buildUrlIconValue(url: string): string {
  return `url:${url.trim()}`
}

export function buildCustomClassIconValue(className: string): string {
  return `custom:${className.trim()}`
}

export function buildMediaIconValue(mediaId: string): string {
  return `media:${mediaId}`
}

export function isImageUrl(value: string): boolean {
  return URL_LIKE.test(value)
}
